import React, { useState } from 'react';
import { ResearchPaper, ResearchField } from '../types/research';
import {
  calculateTotalWordCount,
  downloadPaperAsTxt,
  copyTextToClipboard,
  formatCitation,
} from '../utils/exporter';
import {
  History,
  Search,
  Filter,
  Download,
  Copy,
  Check,
  Trash2,
  ExternalLink,
  BookOpen,
  Calendar,
  Layers,
  Sparkles,
  ArrowRight,
  ShieldCheck,
  FileText,
} from 'lucide-react';

interface ResearchHistorySectionProps {
  papers: ResearchPaper[];
  onSelectPaper: (paper: ResearchPaper) => void;
  onDeletePaper: (id: string, e: React.MouseEvent) => void;
  onClearAll: () => void;
  onNewProposal: () => void;
  currentPaperId?: string;
}

export const ResearchHistorySection: React.FC<ResearchHistorySectionProps> = ({
  papers,
  onSelectPaper,
  onDeletePaper,
  onClearAll,
  onNewProposal,
  currentPaperId,
}) => {
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedField, setSelectedField] = useState<string>('All');
  const [copiedId, setCopiedId] = useState<string | null>(null);

  // Compute dashboard metrics across history
  const totalProposals = papers.length;
  const totalWords = papers.reduce((sum, p) => sum + calculateTotalWordCount(p), 0);
  const totalLandmarks = papers.reduce(
    (sum, p) =>
      sum + (p.references?.filter((r) => r.verificationStatus === 'verified_landmark').length || 0),
    0
  );
  const uniqueFields = new Set(papers.map((p) => p.field)).size;

  const filteredPapers = papers.filter((paper) => {
    const matchesSearch =
      paper.paperTitle.toLowerCase().includes(searchQuery.toLowerCase()) ||
      paper.topic.toLowerCase().includes(searchQuery.toLowerCase()) ||
      paper.abstract.toLowerCase().includes(searchQuery.toLowerCase());

    const matchesField = selectedField === 'All' || paper.field === selectedField;

    return matchesSearch && matchesField;
  });

  const handleCopyCitation = async (paper: ResearchPaper, e: React.MouseEvent) => {
    e.stopPropagation();
    const citationString = `${paper.paperTitle}. Generated by ResearchMate AI (${new Date(
      paper.createdAt
    ).getFullYear()}). Field: ${paper.field}.`;
    const success = await copyTextToClipboard(citationString);
    if (success) {
      setCopiedId(paper.id);
      setTimeout(() => setCopiedId(null), 2000);
    }
  };

  const handleDownload = (paper: ResearchPaper, e: React.MouseEvent) => {
    e.stopPropagation();
    downloadPaperAsTxt(paper);
  };

  return (
    <section id="research-history" className="space-y-6">
      {/* Section Masthead */}
      <div className="bg-white rounded-2xl border border-slate-200/90 p-6 sm:p-8 shadow-xs">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-6 border-b border-slate-100">
          <div>
            <div className="flex items-center gap-2">
              <div className="w-8 h-8 rounded-lg bg-blue-50 text-blue-600 flex items-center justify-center">
                <History className="w-4.5 h-4.5" />
              </div>
              <h2 className="text-xl sm:text-2xl font-bold tracking-tight text-slate-900">
                Research Proposal Archive &amp; History
              </h2>
            </div>
            <p className="text-xs sm:text-sm text-slate-500 mt-1">
              Review, compare, reload, and export all research proposals synthesized in your local workspace.
            </p>
          </div>

          <div className="flex items-center gap-2.5 shrink-0">
            {papers.length > 0 && (
              <button
                type="button"
                onClick={onClearAll}
                className="px-3.5 py-2 text-xs font-semibold text-rose-600 hover:text-rose-700 bg-rose-50/60 hover:bg-rose-100/70 border border-rose-200/60 rounded-xl transition-colors"
              >
                Clear History
              </button>
            )}
            <button
              type="button"
              onClick={onNewProposal}
              className="px-4 py-2 text-xs font-semibold text-white bg-blue-600 hover:bg-blue-700 rounded-xl transition-colors shadow-xs flex items-center gap-1.5"
            >
              <Sparkles className="w-3.5 h-3.5" />
              <span>Formulate New Topic</span>
            </button>
          </div>
        </div>

        {/* Dashboard Aggregate Metrics Bar */}
        <div className="grid grid-cols-2 lg:grid-cols-4 gap-4 pt-6">
          <div className="p-4 rounded-xl bg-slate-50/80 border border-slate-100">
            <span className="text-2xs font-semibold text-slate-400 uppercase tracking-wider block">
              Proposals Formulated
            </span>
            <span className="font-mono text-2xl font-extrabold text-blue-600 tabular-nums">
              {totalProposals}
            </span>
          </div>

          <div className="p-4 rounded-xl bg-slate-50/80 border border-slate-100">
            <span className="text-2xs font-semibold text-slate-400 uppercase tracking-wider block">
              Total Words Synthesized
            </span>
            <span className="font-mono text-2xl font-extrabold text-slate-900 tabular-nums">
              {totalWords.toLocaleString()}
            </span>
          </div>

          <div className="p-4 rounded-xl bg-slate-50/80 border border-slate-100">
            <span className="text-2xs font-semibold text-slate-400 uppercase tracking-wider block">
              Verified Landmark Citations
            </span>
            <span className="font-mono text-2xl font-extrabold text-emerald-600 tabular-nums">
              {totalLandmarks}
            </span>
          </div>

          <div className="p-4 rounded-xl bg-slate-50/80 border border-slate-100">
            <span className="text-2xs font-semibold text-slate-400 uppercase tracking-wider block">
              Disciplines Explored
            </span>
            <span className="font-mono text-2xl font-extrabold text-slate-900 tabular-nums">
              {uniqueFields}
            </span>
          </div>
        </div>
      </div>

      {/* Filter and Search Controls */}
      <div className="bg-white rounded-xl border border-slate-200/90 p-4 shadow-2xs flex flex-col md:flex-row items-center justify-between gap-4">
        {/* Search */}
        <div className="relative w-full md:w-80">
          <Search className="w-4 h-4 text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2 pointer-events-none" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="Search proposals by title or topic..."
            className="w-full pl-9 pr-4 py-2 text-xs text-slate-900 bg-slate-50 rounded-lg border border-slate-200 focus:bg-white focus:border-blue-500 focus:ring-2 focus:ring-blue-100 outline-none transition-all placeholder:text-slate-400"
          />
        </div>

        {/* Field Filters */}
        <div className="flex items-center gap-1.5 overflow-x-auto w-full md:w-auto pb-1 md:pb-0 text-xs">
          {['All', 'Computer Science', 'Engineering', 'Medicine', 'Environment', 'Business'].map(
            (field) => (
              <button
                key={field}
                type="button"
                onClick={() => setSelectedField(field)}
                className={`px-3 py-1.5 rounded-lg font-medium whitespace-nowrap transition-colors ${
                  selectedField === field
                    ? 'bg-blue-600 text-white shadow-2xs'
                    : 'bg-slate-100/80 text-slate-600 hover:text-slate-900 hover:bg-slate-200/60'
                }`}
              >
                {field}
              </button>
            )
          )}
        </div>
      </div>

      {/* Papers Grid */}
      {filteredPapers.length === 0 ? (
        <div className="bg-white rounded-2xl border border-slate-200/90 p-12 text-center max-w-lg mx-auto">
          <BookOpen className="w-12 h-12 text-slate-300 mx-auto mb-3" />
          <h3 className="text-base font-bold text-slate-900">
            {papers.length === 0 ? 'No Research Proposals Yet' : 'No Matching Proposals'}
          </h3>
          <p className="text-xs text-slate-500 mt-1 max-w-sm mx-auto">
            {papers.length === 0
              ? 'Enter a research inquiry in the Proposal Generator to formulate your first paper.'
              : 'Try clearing your search query or choosing another field filter.'}
          </p>
          {papers.length === 0 && (
            <button
              type="button"
              onClick={onNewProposal}
              className="mt-4 px-4 py-2 text-xs font-semibold text-white bg-blue-600 hover:bg-blue-700 rounded-xl transition-colors inline-flex items-center gap-1.5 shadow-xs"
            >
              <Sparkles className="w-3.5 h-3.5" />
              <span>Create First Proposal</span>
            </button>
          )}
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
          {filteredPapers.map((paper) => {
            const isSelected = paper.id === currentPaperId;
            const words = calculateTotalWordCount(paper);
            const verifiedLandmarks =
              paper.references?.filter((r) => r.verificationStatus === 'verified_landmark').length ||
              0;
            const formattedDate = new Date(paper.createdAt).toLocaleDateString('en-US', {
              year: 'numeric',
              month: 'short',
              day: 'numeric',
            });

            return (
              <div
                key={paper.id}
                onClick={() => onSelectPaper(paper)}
                className={`bg-white rounded-xl border p-5 transition-all cursor-pointer relative group flex flex-col justify-between ${
                  isSelected
                    ? 'border-blue-500 ring-2 ring-blue-100 shadow-sm'
                    : 'border-slate-200/90 hover:border-slate-300 hover:shadow-xs'
                }`}
              >
                <div className="space-y-3">
                  {/* Top unboxed metadata */}
                  <div className="flex items-center justify-between gap-2 text-2xs text-slate-500 font-medium">
                    <div className="flex items-center gap-1.5">
                      <span className="font-semibold text-blue-700">{paper.field}</span>
                      <span aria-hidden="true">·</span>
                      <span className="font-mono tabular-nums">{formattedDate}</span>
                    </div>

                    <div className="flex items-center gap-1.5 font-mono tabular-nums">
                      <span>{words} words</span>
                      <span aria-hidden="true">·</span>
                      <span className="text-emerald-700 font-semibold">{verifiedLandmarks} verified</span>
                    </div>
                  </div>

                  {/* Title */}
                  <h3 className="text-sm sm:text-base font-bold text-slate-900 group-hover:text-blue-600 transition-colors line-clamp-2 leading-snug">
                    {paper.paperTitle}
                  </h3>

                  {/* Abstract Snippet */}
                  <p className="text-xs text-slate-600 line-clamp-2 leading-relaxed">
                    {paper.abstract}
                  </p>
                </div>

                {/* Bottom Action Bar */}
                <div className="mt-4 pt-3 border-t border-slate-100 flex items-center justify-between gap-2 text-xs">
                  <span className="text-2xs text-slate-400 truncate max-w-[160px]">
                    Inquiry: {paper.topic}
                  </span>

                  <div className="flex items-center gap-1.5 shrink-0">
                    <button
                      type="button"
                      onClick={(e) => handleCopyCitation(paper, e)}
                      className="p-1.5 text-slate-400 hover:text-blue-600 hover:bg-blue-50 rounded-lg transition-colors"
                      title="Copy paper reference"
                    >
                      {copiedId === paper.id ? (
                        <Check className="w-3.5 h-3.5 text-emerald-600" />
                      ) : (
                        <Copy className="w-3.5 h-3.5" />
                      )}
                    </button>

                    <button
                      type="button"
                      onClick={(e) => handleDownload(paper, e)}
                      className="p-1.5 text-slate-400 hover:text-blue-600 hover:bg-blue-50 rounded-lg transition-colors"
                      title="Download as TXT"
                    >
                      <Download className="w-3.5 h-3.5" />
                    </button>

                    <button
                      type="button"
                      onClick={(e) => onDeletePaper(paper.id, e)}
                      className="p-1.5 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-lg transition-colors"
                      title="Delete proposal"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>

                    <button
                      type="button"
                      onClick={() => onSelectPaper(paper)}
                      className="ml-1 px-2.5 py-1 text-2xs font-semibold text-blue-700 bg-blue-50 hover:bg-blue-100 rounded-lg transition-colors flex items-center gap-1"
                    >
                      <span>Open</span>
                      <ArrowRight className="w-3 h-3" />
                    </button>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </section>
  );
};
